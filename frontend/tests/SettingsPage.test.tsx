it('统一保存等待应用成功后写入浏览器偏好，保存期间锁定全部表单', async () => {
  let finishSave!: (value: applicationSettings.ApplicationSettings) => void
  vi.mocked(applicationSettings.fetchApplicationSettings).mockResolvedValue(applicationExample)
  vi.mocked(applicationSettings.saveApplicationSettings).mockReturnValue(new Promise(resolve => { finishSave = resolve }))
  renderWithProviders(<SettingsPage />)
  const font = screen.getByLabelText('正文字号')
  fireEvent.change(font, { target: { value: '21' } })
  await selectCategory('自动处理')
  const thinking = screen.getByTestId('processing-thinking-mode')
  await userEvent.selectOptions(thinking, 'enabled')
  await selectCategory('应用配置')
  const port = await screen.findByLabelText('服务端口')
  fireEvent.change(port, { target: { value: '8800' } })
  await selectCategory('阅读显示')
  const save = settingsSaveButton()
  await userEvent.click(save)
  await waitFor(() => expect(applicationSettings.saveApplicationSettings).toHaveBeenCalledTimes(1))
  expect(save).toBeDisabled()
  expect(font).toBeDisabled()
  expect(port).toBeDisabled()
  expect(thinking).toBeDisabled()
  expect(screen.getByRole('button', { name: '恢复阅读显示默认值' })).toBeDisabled()
  expect(getGeneralSettings().fontSize).toBe(16)
  expect(getProcessingPreferences().thinkingMode).toBe('default')
  await userEvent.type(font, '9')
  expect(font).toHaveValue(21)
  await act(async () => finishSave({ ...applicationExample, revision: 'saved', restart_required: ['port'],
    fields: [{ ...applicationExample.fields[0], value: 8800 }] }))
  await waitFor(() => expect(getGeneralSettings().fontSize).toBe(21))
  expect(getProcessingPreferences().thinkingMode).toBe('enabled')
  expect(font).toBeEnabled()
  expect(port).toBeEnabled()
  expect(settingsSaveButton()).toBeDisabled()
})
